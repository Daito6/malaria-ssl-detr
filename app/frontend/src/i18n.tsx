const DICTS: Record<Lang, Record<Key, string>> = { uk, en };

export type TFn = (key: Key, vars?: Record<string, string | number>) => string;

interface I18n {
  lang: Lang;
  setLang: (l: Lang) => void;
  t: TFn;
  /** Translation if the key exists (e.g. server error codes), else undefined. */
  maybe: (key: string) => string | undefined;
}

const Ctx = createContext<I18n | null>(null);

function initialLang(): Lang {
  try {
    const v = localStorage.getItem("smearscan.lang");
    if (v === "uk" || v === "en") return v;
  } catch {
    /* storage unavailable */
  }
  return "uk";
}

export function I18nProvider({ children }: { children: ReactNode }) {
  const [lang, setLangState] = useState<Lang>(initialLang);
  const setLang = useCallback((l: Lang) => {
    setLangState(l);
    document.documentElement.lang = l;
    try {
      localStorage.setItem("smearscan.lang", l);
    } catch {
      /* storage unavailable */
    }
  }, []);
  const value = useMemo<I18n>(() => {
    const dict = DICTS[lang];
    const t: TFn = (key, vars) =>
      dict[key].replace(/\{(\w+)\}/g, (_, k: string) => (vars && k in vars ? String(vars[k]) : `{${k}}`));
    return { lang, setLang, t, maybe: (key) => (key in dict ? dict[key as Key] : undefined) };
  }, [lang, setLang]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export function useI18n(): I18n {
  const v = useContext(Ctx);
  if (!v) throw new Error("useI18n outside I18nProvider");
  return v;
}
